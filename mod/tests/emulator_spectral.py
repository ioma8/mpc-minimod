"""Exercise the actual menu and independently read back the release chop model.

Requires the lab's demo project with GuitPh-Grove3 E85 91V on A13 (62259
frames), the release
minimod.so preloaded, and the matching linker map generated by mod/build.sh.
See docs/re/SPECTRAL-CHOP-SOLVED.md for build and invocation commands.
This changes the selected sample's chop; it never saves or resets the project.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shlex
import struct
import subprocess
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lab', type=Path, required=True)
    parser.add_argument('--boots', type=int, default=1)
    parser.add_argument('--library', type=Path, default=ROOT / 'build/minimod.so')
    parser.add_argument('--mapfile', type=Path, default=ROOT / 'build/minimod.map')
    args = parser.parse_args()
    symbols = {}
    for line in args.mapfile.read_text().splitlines():
        fields = line.split()
        if fields and fields[-1] == 'g_screen':
            symbols['g_screen'] = int(fields[0], 16)
    assert 'g_screen' in symbols, 'Missing g_screen in linker map'
    spec = importlib.util.spec_from_file_location('lab', args.lab / 'lab.py')
    lab = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(lab)
    panel = f'http://{lab.HOST}:{lab.PORTS["panel"]}'
    def ssh(command):
        return subprocess.check_output(['ssh', *lab.ssh_base(), 'root@' + lab.HOST,
                                        command], timeout=15)
    def control(name, action, value=0):
        body = json.dumps(dict(name=name, action=action, value=value)).encode()
        req = urllib.request.Request(panel + '/control', data=body,
                                     headers={'Content-Type': 'application/json'})
        with urllib.request.urlopen(req, timeout=5) as response:
            assert json.load(response)['ok']
        time.sleep(.08)
    def tap(name):
        control(name, 'press', 100)
        control(name, 'release')
    def chop_mode():
        with urllib.request.urlopen(panel + '/state?since=0', timeout=5) as response:
            return json.load(response)['leds'].get('75', 0) == 2
    def run_chop():
        control('SHIFT', 'press', 127)
        tap('DATA')
        control('SHIFT', 'release')
        control('DATA', 'turn', 1)
        tap('DATA')
        time.sleep(.8)
    expected = [264, 14187, 30059, 45419, 54635]
    expected_pairs = list(zip(expected, expected[1:] + [62259]))
    for boot in range(args.boots):
        ssh('systemctl restart ac50')
        time.sleep(5)
        pid = int(ssh('pidof "MPC Sample"'))
        baseline_restarts = ssh('systemctl show ac50 -p NRestarts')
        maps = ssh(f'cat /proc/{pid}/maps').decode().splitlines()
        mapping = next((x for x in maps if x.endswith('/' + args.library.name)), None)
        assert mapping is not None, (
            f'{args.library.name} is not mapped into the app; preload it first with '
            '`python3 lab.py preload <repo>/mod/build/minimod.so`')
        base = int(mapping.split('-')[0], 16)
        remote = mapping.split()[-1]
        digest = ssh('sha256sum ' + shlex.quote(remote)).decode().split()[0]
        assert digest == hashlib.sha256(args.library.read_bytes()).hexdigest()
        def memory(address, size):
            data = ssh(f'dd if=/proc/{pid}/mem bs=1 skip={address} count={size} 2>/dev/null')
            assert len(data) == size, 'App died or model address became invalid'
            return data
        def qword(address):
            return struct.unpack('<Q', memory(address, 8))[0]
        def model():
            screen = qword(base + symbols['g_screen'])
            stock = int(next(x.split('-')[0] for x in maps if x.endswith('/MPC Sample')), 16)
            assert qword(screen) == stock + 0x6e212a0, 'Wrong map or Sample screen unavailable'
            binding = qword(screen + 0x178)
            state = qword(binding + 0x60)
            sample = qword(qword(state + 0x22e8) + 0x4a8)
            meta = qword(sample + 0x130)
            frames = struct.unpack('<I', memory(meta + 4, 4))[0]
            assert frames == 62259, 'Load GuitPh-Grove3 on A13 first'
            begin, end = struct.unpack('<QQ', memory(meta + 0x70, 16))
            count = (end - begin) // 8
            assert 0 <= count <= 16
            pointers = struct.unpack('<' + 'Q' * count, memory(begin, count * 8)) if count else []
            pairs = []
            for pointer in pointers:
                blob = memory(pointer + 0x78, 0x60)
                pairs.append((struct.unpack_from('<Q', blob)[0],
                              struct.unpack_from('<Q', blob, 0x58)[0]))
            kind = struct.unpack('<i', memory(qword(screen + 0x168) + 0x9c, 4))[0]
            return sample, kind, pairs
        if chop_mode():
            tap('CHOP')
            time.sleep(.3)
        tap('PAD 13')
        time.sleep(.3)
        source = model()[0]
        for case in ['first from Trim', 'repeat', 'repeat again', 'regions', 'threshold', 'after pad playback']:
            if case in ('regions', 'threshold'):
                control('K3', 'set', 64 if case == 'regions' else 0)
                time.sleep(.9)
                print(f'boot {boot + 1}: {case} initial type={model()[1]}', flush=True)
            if case == 'after pad playback':
                for pad in (1, 5, 10, 16):
                    tap('PAD ' + str(pad))
            run_chop()
            actual = model()
            assert actual == (source, 0, expected_pairs), (case, actual)
            assert int(ssh('pidof "MPC Sample"')) == pid, 'Firmware restarted'
            assert ssh('systemctl show ac50 -p NRestarts') == baseline_restarts
            print(f'PASS boot {boot + 1}: {case}; exact 5 boundaries, Manual, pid={pid}', flush=True)
        # Native notifications must retain the result through view reconstruction.
        tap('CHOP')
        time.sleep(.3)
        tap('CHOP')
        time.sleep(.5)
        assert model() == (source, 0, expected_pairs), 'Re-entering Chop lost the markers'
        urllib.request.urlretrieve(panel + '/screen.png', f'/tmp/spectral-boot-{boot + 1}.png')
    print('PASS: menu, model, repeat, modes, playback, re-entry and restart checks')


if __name__ == '__main__':
    main()
