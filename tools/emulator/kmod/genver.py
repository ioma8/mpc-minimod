import struct, sys
A='/tmp/mpcwork/kh/usr/src/linux-headers-6.12.107+deb13-arm64'
d=open(sys.argv[1],'rb').read()
e_shoff=struct.unpack_from('<Q',d,0x28)[0]; es=struct.unpack_from('<H',d,0x3a)[0]
en=struct.unpack_from('<H',d,0x3c)[0]; si=struct.unpack_from('<H',d,0x3e)[0]
def sh(i):
    o=e_shoff+i*es
    return dict(name=struct.unpack_from('<I',d,o)[0], off=struct.unpack_from('<Q',d,o+0x18)[0],
                size=struct.unpack_from('<Q',d,o+0x20)[0], link=struct.unpack_from('<I',d,o+0x28)[0])
strtab=d[sh(si)['off']:sh(si)['off']+sh(si)['size']]
def nm(n):
    e=strtab.find(b'\0',n); return strtab[n:e].decode()
und=set()
for i in range(en):
    s=sh(i)
    if nm(s['name'])=='.symtab':
        st=d[s['off']:s['off']+s['size']]; stn=sh(s['link'])
        stt=d[stn['off']:stn['off']+stn['size']]
        for k in range(s['size']//24):
            o=k*24; n=struct.unpack_from('<I',st,o)[0]
            info=struct.unpack_from('<B',st,o+4)[0]; shndx=struct.unpack_from('<H',st,o+6)[0]
            if shndx==0 and info>>4==1:
                e=stt.find(b'\0',n); und.add(stt[n:e].decode())
crc={}
for line in open(A+'/Module.symvers'):
    p=line.rstrip('\n').split('\t')
    if len(p)>=2: crc[p[1]]=p[0]
und.add('module_layout')
out=['/* generated by genver.py: modversion_info + __this_module (modpost normally does this) */',
     '#include <linux/module.h>',
     'static const char __attribute__((section(".modinfo"), used)) __vm[] = "vermagic=" "6.12.107+deb13-arm64 SMP mod_unload modversions aarch64";',
     'struct modversion_info __attribute__((section("__versions"), used)) ____versions[] = {']
for s in sorted(und):
    if s in crc: out.append('    { %sUL, "%s" },' % (crc[s], s))
out.append('};')
out.append('struct module __this_module __attribute__((section(".gnu.linkonce.this_module"))) = {')
out.append('    .name = KBUILD_MODNAME,\n    .init = init_module,\n    .exit = cleanup_module,\n};')
open('versions.h','w').write('\n'.join(out)+'\n')
print("symbols:", len(und), "-> CRCs written:", sum(1 for s in und if s in crc))
